// Copies the preference pane controller into the addon assets.
//
// `src/ui/prefs-pane.js` is a plain classic script (it is loaded into the
// preferences window, where ES modules are unavailable), so it cannot simply be
// imported by the bundle. The plugin also embeds it as a string through a
// `?raw` import, which keeps a single source of truth; this script only makes
// sure the shipped copy in `addon/` matches.
//
// Usage:
//   node tools/build-prefs-pane.cjs          # (re)write addon/prefs-pane.js
//   node tools/build-prefs-pane.cjs --check  # fail when it is out of date
const fs = require("fs");
const path = require("path");

const root = process.cwd();
const source = path.join(root, "src/ui/prefs-pane.js");
const target = path.join(root, "addon/chrome/content/prefs-pane.js");

const banner = `/*
 * Generated from src/ui/prefs-pane.js by tools/build-prefs-pane.cjs.
 * Do not edit this file directly.
 */
`;

const contents = banner + fs.readFileSync(source, "utf8");
const checkOnly = process.argv.includes("--check");

if (checkOnly) {
  const existing = fs.existsSync(target) ? fs.readFileSync(target, "utf8") : "";
  if (existing !== contents) {
    console.error(
      "addon/chrome/content/prefs-pane.js is out of date. Run: node tools/build-prefs-pane.cjs",
    );
    process.exit(1);
  }
  console.log("addon/chrome/content/prefs-pane.js is up to date");
  process.exit(0);
}

fs.mkdirSync(path.dirname(target), { recursive: true });
fs.writeFileSync(target, contents);
console.log(`wrote ${path.relative(root, target)}`);
